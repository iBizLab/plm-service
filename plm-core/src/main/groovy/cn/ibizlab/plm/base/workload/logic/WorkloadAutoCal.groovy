import net.ibizsys.model.dataentity.logic.IPSDELogicNode

import org.apache.commons.logging.Log
import org.apache.commons.logging.LogFactory

/**
 * 实体[WORKLOAD]处理逻辑[工时自动计算]运行时对象
 * 此代码用户功能扩展代码
 *
 * 修改当前逻辑，在当前逻辑内进行递归调用，调用别的逻辑，不去调用原保存变更逻辑了。
 */
class WorkloadAutoCal extends DELogicRuntime {

    private static final Log log = LogFactory.getLog(WorkloadAutoCal.class)

    @Override
	protected void onInit() throws Exception {
		super.onInit()
	}

    @Override
    protected void onExecutePSDELogicNode(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        switch (iPSDELogicNode.getCodeName()) {
            case "Begin":
                //执行逻辑节点[开始]
                executeBegin(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL1":
                //执行逻辑节点[计算父工作项汇聚工时]
                executeRAWSQLCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSFCODE2":
                //执行逻辑节点[计算剩余工时]
                executeRAWSFCODE2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM7":
                //执行逻辑节点[设置实际工时]
                executePREPAREPARAM7(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION4":
                //执行逻辑节点[保存实际工时]
                executeDEACTION4(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM8":
                //执行逻辑节点[设置剩余工时]
                executePREPAREPARAM8(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION5":
                //执行逻辑节点[保存剩余工时]
                executeDEACTION5(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM9":
                //执行逻辑节点[填充递归调用参数]
                executePREPAREPARAM9(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION3":
                //执行逻辑节点[获取父工作项]
                executeDEACTION3(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM2":
                //执行逻辑节点[设置父工作项ID]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "DELOGIC1":
                //执行逻辑节点[递归调用]
                executeDELOGIC1(iDELogicSession, iPSDELogicNode)
                break
            case "END1":
                //执行逻辑节点[结束]
                executeEND1(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

    /**
     * 执行逻辑节点[开始]，逻辑类型[BEGIN]
     * @param iDELogicSession
     * @param iPSDELogicNode
     * @throws Throwable
     */
    private void executeBegin(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode, true)
    }

    /**
     * 执行逻辑节点[计算父工作项汇聚工时]，逻辑类型[RAWSQLCALL]
     * @param iDELogicSession
     * @param iPSDELogicNode
     * @throws Throwable
     */
    private void executeRAWSQLCALL1(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode, true)
    }

    /**
     * 执行逻辑节点[计算剩余工时]，逻辑类型[RAWSFCODE]
