                //执行逻辑节点[上级的是否叶子节点变更]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "DEDATASET3":
                //执行逻辑节点[模块下模块]
                executeDEDATASET3(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL1":
                //执行逻辑节点[修改需求信息]
                executeRAWSQLCALL1(iDELogicSession, iPSDELogicNode)
                break
