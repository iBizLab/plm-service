    private static final Log log = LogFactory.getLog(SaveWorkload.class)

    @Override
	protected void onInit() throws Exception {
		super.onInit()
	}

    @Override
    protected void onExecutePSDELogicNode(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        switch (iPSDELogicNode.getCodeName()) {
            case "Begin":
                //执行逻辑节点[开始]
                executeBegin(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM1":
                //执行逻辑节点[调试逻辑参数]
                executeDEBUGPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM2":
                //执行逻辑节点[绑定所属对象标识]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION3":
                //执行逻辑节点[获取需求]
                executeDEACTION3(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION4":
                //执行逻辑节点[获取工作项]
                executeDEACTION4(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION5":
                //执行逻辑节点[获取测试用例]
                executeDEACTION5(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM3":
                //执行逻辑节点[工作项和项目信息属性]
                executePREPAREPARAM3(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM4":
                //执行逻辑节点[产品需求和产品信息属性]
                executePREPAREPARAM4(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM5":
                //执行逻辑节点[测试用例和测试库信息属性]
                executePREPAREPARAM5(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION2":
                //执行逻辑节点[保存工时]
                executeDEACTION2(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION6":
                //执行逻辑节点[更新剩余工时]
                executeDEACTION6(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM6":
                //执行逻辑节点[工时为0时置为NULL]
                executePREPAREPARAM6(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL1":
                //执行逻辑节点[合计已登记工时]
                executeRAWSQLCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION7":
                //执行逻辑节点[更新实际工时]
                executeDEACTION7(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM7":
                //执行逻辑节点[填充父工作项标识]
                executePREPAREPARAM7(iDELogicSession, iPSDELogicNode)
                break
            case "DELOGIC1":
                //执行逻辑节点[自动计算父工时]
                executeDELOGIC1(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

    /**
