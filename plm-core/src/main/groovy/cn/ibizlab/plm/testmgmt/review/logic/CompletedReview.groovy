/**
 * 实体[REVIEW]处理逻辑[完成评审]运行时对象
 * 此代码用户功能扩展代码
 *
 * 完成评审，修改评审状态以及设置那些未评审用例的评审结果
 */
class CompletedReview extends DELogicRuntime {

    private static final Log log = LogFactory.getLog(CompletedReview.class)

    @Override
