                //执行逻辑节点[结束]
                executeEND1(iDELogicSession, iPSDELogicNode)
                break
            case "LOOPSUBCALL2":
                //执行逻辑节点[循环子调用]
                executeLOOPSUBCALL2(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL1":
                //执行逻辑节点[直接SQL调用]
                executeRAWSQLCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM1":
                //执行逻辑节点[返回未规划数据]
                executeDEBUGPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "LOOPSUBCALL1":
                //执行逻辑节点[循环子调用]
                executeLOOPSUBCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM3":
                //执行逻辑节点[设置测试用例ID]
                executePREPAREPARAM3(iDELogicSession, iPSDELogicNode)
                break
            case "COPYPARAM1":
                //执行逻辑节点[拷贝创建参数]
                executeCOPYPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION2":
                //执行逻辑节点[获取测试用例详情]
                executeDEACTION2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM2":
                //执行逻辑节点[准备执行用例数据]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION1":
                //执行逻辑节点[创建执行用例]
                executeDEACTION1(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

