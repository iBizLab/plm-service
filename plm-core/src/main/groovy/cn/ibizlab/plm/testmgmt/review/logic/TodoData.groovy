                break
            case "PREPAREPARAM2":
                //执行逻辑节点[设置申请对象参数]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "APPENDPARAM1":
                //执行逻辑节点[附加到数组参数]
                executeAPPENDPARAM1(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

