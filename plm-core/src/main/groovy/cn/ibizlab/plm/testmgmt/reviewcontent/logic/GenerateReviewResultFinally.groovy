/**
 * 实体[REVIEW_CONTENT]处理逻辑[生成最终评审结果]运行时对象
 * 此代码用户功能扩展代码
 *
 * 评审完成后生成最终的评审结果
 */
class GenerateReviewResultFinally extends DELogicRuntime {

    private static final Log log = LogFactory.getLog(GenerateReviewResultFinally.class)

    @Override
	protected void onInit() throws Exception {
		super.onInit()
	}

    @Override
    protected void onExecutePSDELogicNode(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        switch (iPSDELogicNode.getCodeName()) {
            case "Begin":
                //执行逻辑节点[开始]
                executeBegin(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM5":
                //执行逻辑节点[设置通过]
                executePREPAREPARAM5(iDELogicSession, iPSDELogicNode)
                break
            case "END1":
                //执行逻辑节点[结束]
                executeEND1(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM4":
                //执行逻辑节点[调试逻辑参数]
                executeDEBUGPARAM4(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM3":
                //执行逻辑节点[调试逻辑参数]
                executeDEBUGPARAM3(iDELogicSession, iPSDELogicNode)
                break
            case "DEDATASET1":
                //执行逻辑节点[获取评审内容数据集]
                executeDEDATASET1(iDELogicSession, iPSDELogicNode)
                break
            case "LOOPSUBCALL2":
                //执行逻辑节点[循环子调用]
                executeLOOPSUBCALL2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM1":
                //执行逻辑节点[绑定评审结果]
                executePREPAREPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "LOOPSUBCALL1":
                //执行逻辑节点[循环子调用]
                executeLOOPSUBCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION1":
                //执行逻辑节点[处理每一个内容]
                executeDEACTION1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM7":
                //执行逻辑节点[设置评审内容过滤器]
                executePREPAREPARAM7(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM2":
                //执行逻辑节点[调试逻辑参数]
                executeDEBUGPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM6":
                //执行逻辑节点[设置拒绝]
                executePREPAREPARAM6(iDELogicSession, iPSDELogicNode)
                break
            case "END2":
                //执行逻辑节点[跳出]
                executeEND2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM2":
                //执行逻辑节点[可以生成最终评审结果]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM3":
                //执行逻辑节点[不可生成最终评审结果]
                executePREPAREPARAM3(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM4":
                //执行逻辑节点[设置最终结果]
                executePREPAREPARAM4(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

    /**
