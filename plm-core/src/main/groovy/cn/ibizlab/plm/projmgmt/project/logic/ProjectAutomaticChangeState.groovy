/**
 * 实体[PROJECT]处理逻辑[项目自动变更状态]运行时对象
 * 此代码用户功能扩展代码
 *
 * 定时执行，当项目的结束时间小于当前日期时，自动将项目状态变更为延期；
当项目的结束时间距今不足五天时，自动将项目状态变更为预警；
 */
class ProjectAutomaticChangeState extends DELogicRuntime {

    private static final Log log = LogFactory.getLog(ProjectAutomaticChangeState.class)

    @Override
	protected void onInit() throws Exception {
		super.onInit()
	}

    @Override
    protected void onExecutePSDELogicNode(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        switch (iPSDELogicNode.getCodeName()) {
            case "Begin":
                //执行逻辑节点[开始]
                executeBegin(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM1":
                //执行逻辑节点[设置逾期项目过滤条件]
                executePREPAREPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "DEDATASET1":
                //执行逻辑节点[获取符合条件的逾期项目]
                executeDEDATASET1(iDELogicSession, iPSDELogicNode)
                break
            case "END2":
                //执行逻辑节点[结束]
                executeEND2(iDELogicSession, iPSDELogicNode)
                break
            case "LOOPSUBCALL1":
                //执行逻辑节点[循环执行]
                executeLOOPSUBCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSFCODE1":
                //执行逻辑节点[执行脚本代码]
                executeRAWSFCODE1(iDELogicSession, iPSDELogicNode)
                break
            case "DEBUGPARAM1":
                //执行逻辑节点[调试逻辑参数]
                executeDEBUGPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM3":
                //执行逻辑节点[空节点，承载判断]
                executePREPAREPARAM3(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL1":
                //执行逻辑节点[判断当前项目是否存在工作项]
                executeRAWSQLCALL1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM2":
                //执行逻辑节点[设置状态为延期]
                executePREPAREPARAM2(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM4":
                //执行逻辑节点[设置状态为预警]
                executePREPAREPARAM4(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM7":
                //执行逻辑节点[设置状态为正常]
                executePREPAREPARAM7(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM5":
                //执行逻辑节点[设置状态为正常]
                executePREPAREPARAM5(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL2":
                //执行逻辑节点[汇聚预计、消耗工时]
                executeRAWSQLCALL2(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL3":
                //执行逻辑节点[直接SQL调用]
                executeRAWSQLCALL3(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM6":
                //执行逻辑节点[准备参数]
                executePREPAREPARAM6(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION1":
                //执行逻辑节点[更新项目状态]
                executeDEACTION1(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

    /**
