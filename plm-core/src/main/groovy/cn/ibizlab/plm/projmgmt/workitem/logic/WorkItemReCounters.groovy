    @Override
    protected void onExecutePSDELogicNode(IDELogicSession iDELogicSession, IPSDELogicNode iPSDELogicNode) throws Throwable {
        switch (iPSDELogicNode.getCodeName()) {
            case "Begin":
                //执行逻辑节点[开始]
                executeBegin(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL12":
                //执行逻辑节点[合并查询计数器]
                executeRAWSQLCALL12(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL13":
                //执行逻辑节点[工作项依赖]
                executeRAWSQLCALL13(iDELogicSession, iPSDELogicNode)
                break
            case "END2":
                //执行逻辑节点[结束]
                executeEND2(iDELogicSession, iPSDELogicNode)
                break
            case "DEACTION1":
                //执行逻辑节点[获取工作项当前版本]
                executeDEACTION1(iDELogicSession, iPSDELogicNode)
                break
            case "PREPAREPARAM1":
                //执行逻辑节点[准备参数]
                executePREPAREPARAM1(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL2":
                //执行逻辑节点[工作项关联子工作项]
                executeRAWSQLCALL2(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL6":
                //执行逻辑节点[工作项内交付物]
                executeRAWSQLCALL6(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL7":
                //执行逻辑节点[工作项版本]
                executeRAWSQLCALL7(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL8":
                //执行逻辑节点[工作项关联产品需求]
                executeRAWSQLCALL8(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL9":
                //执行逻辑节点[工作项关联工作项]
                executeRAWSQLCALL9(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL10":
                //执行逻辑节点[工作项关联测试用例]
                executeRAWSQLCALL10(iDELogicSession, iPSDELogicNode)
                break
            case "RAWSQLCALL11":
                //执行逻辑节点[工作项关联工单]
                executeRAWSQLCALL11(iDELogicSession, iPSDELogicNode)
                break
            default:
                super.onExecutePSDELogicNode(iDELogicSession, iPSDELogicNode)
        }
    }

